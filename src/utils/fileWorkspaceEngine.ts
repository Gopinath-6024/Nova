import { Document, HeadingLevel, Packer, Paragraph, Table, TableCell, TableRow, TextRun, WidthType } from 'docx';
import JSZip from 'jszip';
import PptxGenJS from 'pptxgenjs';
import * as XLSX from 'xlsx';
import type { ResearchReport, WorkspaceFileFormat } from '../types/nova';
import { createFormattedPdf, downloadBase64Pdf } from './pdfEngine';

function triggerBlobDownload(blob: Blob, fileName: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function safeSlug(name: string): string {
  return (name || 'nova-document')
    .trim()
    .replace(/[^a-zA-Z0-9._-]+/g, '_')
    .replace(/^_+|_+$/g, '') || 'nova_export';
}

export function exportTextFile(text: string, title: string, ext: 'txt' | 'md' | 'csv' | 'html') {
  const mime =
    ext === 'csv'
      ? 'text/csv;charset=utf-8'
      : ext === 'md'
        ? 'text/markdown;charset=utf-8'
        : ext === 'html'
          ? 'text/html;charset=utf-8'
          : 'text/plain;charset=utf-8';
  triggerBlobDownload(new Blob([text], { type: mime }), `${safeSlug(title)}.${ext}`);
}

export async function exportAsDocx(params: {
  title: string;
  subtitle?: string;
  sections: Array<{ heading: string; body: string }>;
  tableHeaders?: string[];
  tableRows?: string[][];
}): Promise<void> {
  const children: Array<Paragraph | Table> = [
    new Paragraph({
      text: params.title || 'NOVA Document',
      heading: HeadingLevel.TITLE,
    }),
  ];

  if (params.subtitle) {
    children.push(
      new Paragraph({
        children: [new TextRun({ text: params.subtitle, italics: true, color: '555555' })],
      })
    );
  }

  for (const sec of params.sections) {
    children.push(
      new Paragraph({
        text: sec.heading,
        heading: HeadingLevel.HEADING_2,
        spacing: { before: 240, after: 100 },
      })
    );
    for (const line of sec.body.split('\n')) {
      if (line.trim()) {
        children.push(
          new Paragraph({
            text: line.trim(),
            spacing: { after: 120 },
          })
        );
      }
    }
  }

  if (params.tableHeaders && params.tableHeaders.length > 0 && params.tableRows) {
    const headerRow = new TableRow({
      children: params.tableHeaders.map(
        (h) =>
          new TableCell({
            width: { size: Math.floor(100 / params.tableHeaders!.length), type: WidthType.PERCENTAGE },
            children: [new Paragraph({ children: [new TextRun({ text: h, bold: true })] })],
          })
      ),
    });
    const bodyRows = params.tableRows.slice(0, 100).map(
      (r) =>
        new TableRow({
          children: params.tableHeaders!.map(
            (_, ci) =>
              new TableCell({
                width: { size: Math.floor(100 / params.tableHeaders!.length), type: WidthType.PERCENTAGE },
                children: [new Paragraph({ text: String(r[ci] ?? '') })],
              })
          ),
        })
    );
    children.push(
      new Table({
        rows: [headerRow, ...bodyRows],
        width: { size: 100, type: WidthType.PERCENTAGE },
      })
    );
  }

  const doc = new Document({ sections: [{ children }] });
  const blob = await Packer.toBlob(doc);
  triggerBlobDownload(blob, `${safeSlug(params.title)}.docx`);
}

export function exportAsXlsx(params: {
  title: string;
  headers: string[];
  rows: string[][];
  format?: 'xlsx' | 'csv';
}): void {
  const aoa = [
    params.headers.length > 0 ? params.headers : ['Column 1'],
    ...(params.rows.length > 0 ? params.rows : [['No tabular rows']]),
  ];
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  if (params.format === 'csv') {
    const csv = XLSX.utils.sheet_to_csv(ws);
    exportTextFile(csv, params.title, 'csv');
    return;
  }
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Sheet1');
  const buf = XLSX.write(wb, { bookType: 'xlsx', type: 'array' }) as ArrayBuffer;
  triggerBlobDownload(
    new Blob([buf], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }),
    `${safeSlug(params.title)}.xlsx`
  );
}

export async function exportAsPptx(params: {
  title: string;
  subtitle?: string;
  sections: Array<{ heading: string; body: string }>;
}): Promise<void> {
  const pptx = new PptxGenJS();
  pptx.layout = 'LAYOUT_16x9';

  const cover = pptx.addSlide();
  cover.background = { color: '0D0917' };
  cover.addText(params.title || 'NOVA Presentation', {
    x: 0.7,
    y: 1.8,
    w: 8.6,
    h: 1.2,
    fontSize: 32,
    bold: true,
    color: 'F4F1FA',
  });
  cover.addText(params.subtitle || `Generated by NOVA File Workspace · ${new Date().toLocaleDateString()}`, {
    x: 0.7,
    y: 3.1,
    w: 8.6,
    h: 0.8,
    fontSize: 15,
    color: 'A78BFA',
  });

  const sections =
    params.sections.length > 0
      ? params.sections
      : [{ heading: 'Overview', body: 'Created in NOVA File Workspace.' }];

  for (const sec of sections.slice(0, 20)) {
    const slide = pptx.addSlide();
    slide.background = { color: '140F24' };
    slide.addText(sec.heading.slice(0, 90), {
      x: 0.6,
      y: 0.5,
      w: 8.8,
      h: 0.7,
      fontSize: 22,
      bold: true,
      color: 'C4B5FD',
    });
    slide.addText(sec.body.slice(0, 1400), {
      x: 0.6,
      y: 1.35,
      w: 8.8,
      h: 3.8,
      fontSize: 14,
      color: 'E2E8F0',
      valign: 'top',
    });
  }

  const out = (await pptx.write({ outputType: 'blob' })) as Blob;
  triggerBlobDownload(out, `${safeSlug(params.title)}.pptx`);
}

export async function exportResearchReport(report: ResearchReport, format: 'pdf' | 'docx'): Promise<void> {
  if (format === 'pdf') {
    const pdf = createFormattedPdf({
      title: report.title || report.query,
      subtitle: `Deep Multi-Source Research Brief · ${report.citations.length} Citations`,
      author: 'NOVA Research Engine',
      sections: [
        {
          heading: 'Executive Summary',
          paragraphs: [report.executiveSummary],
        },
        {
          heading: 'Verified Facts',
          paragraphs: [],
          bullets: report.verifiedFacts.map((f) => `[${f.confidence}] ${f.claim} (${f.sourceLabel})`),
        },
        ...(report.assumptionsAndUncertainties.length > 0
          ? [
              {
                heading: 'Assumptions & Uncertainties',
                paragraphs: [],
                bullets: report.assumptionsAndUncertainties,
              },
            ]
          : []),
        ...(report.conflictingClaims.length > 0
          ? [
              {
                heading: 'Detected Source Conflicts',
                paragraphs: report.conflictingClaims.map(
                  (c) => `${c.topic}: Perspective A — ${c.perspectiveA} | Perspective B — ${c.perspectiveB}`
                ),
              },
            ]
          : []),
        ...report.sections.map((s) => ({
          heading: s.heading,
          paragraphs: s.content.split('\n\n').filter(Boolean),
        })),
        {
          heading: 'Citations',
          paragraphs: [],
          bullets: report.citations.map((c) => `${c.title} — ${c.uri}`),
        },
      ],
    });
    downloadBase64Pdf(pdf.base64Data, report.title || 'nova-research');
    return;
  }

  await exportAsDocx({
    title: report.title || report.query,
    subtitle: `Deep Multi-Source Research Brief · ${report.citations.length} Sources`,
    sections: [
      { heading: 'Executive Summary', body: report.executiveSummary },
      {
        heading: 'Verified Facts',
        body: report.verifiedFacts.map((f) => `• [${f.confidence}] ${f.claim} (${f.sourceLabel})`).join('\n'),
      },
      {
        heading: 'Assumptions & Uncertainties',
        body: report.assumptionsAndUncertainties.map((a) => `• ${a}`).join('\n') || 'None noted.',
      },
      ...(report.conflictingClaims.length > 0
        ? [
            {
              heading: 'Conflicting Claims Across Sources',
              body: report.conflictingClaims
                .map((c) => `Topic: ${c.topic}\n- View A: ${c.perspectiveA}\n- View B: ${c.perspectiveB}`)
                .join('\n\n'),
            },
          ]
        : []),
      ...report.sections.map((s) => ({ heading: s.heading, body: s.content })),
      {
        heading: 'Citations & References',
        body: report.citations.map((c, idx) => `${idx + 1}. ${c.title} (${c.uri})`).join('\n'),
      },
    ],
  });
}

export async function parseUploadedWorkspaceFile(file: File): Promise<{
  name: string;
  format: WorkspaceFileFormat;
  contentText: string;
  tableHeaders?: string[];
  tableRows?: string[][];
}> {
  const ext = (file.name.split('.').pop() || 'txt').toLowerCase();

  if (ext === 'xlsx' || ext === 'xls' || ext === 'csv') {
    const buf = await file.arrayBuffer();
    const wb = XLSX.read(buf, { type: 'array' });
    const firstSheet = wb.SheetNames[0];
    const ws = wb.Sheets[firstSheet];
    const aoa = XLSX.utils.sheet_to_json<string[]>(ws, { header: 1, defval: '' });
    const headers = (aoa[0] ?? []).map(String);
    const rows = aoa.slice(1, 201).map((r) => headers.map((_, ci) => String(r[ci] ?? '')));
    const textPreview = aoa.slice(0, 60).map((r) => r.join(' | ')).join('\n');
    return {
      name: file.name,
      format: ext === 'csv' ? 'csv' : 'xlsx',
      contentText: textPreview,
      tableHeaders: headers,
      tableRows: rows,
    };
  }

  if (ext === 'docx') {
    const zip = await JSZip.loadAsync(await file.arrayBuffer());
    const docXml = await zip.file('word/document.xml')?.async('string');
    if (docXml) {
      const parsed = new DOMParser().parseFromString(docXml, 'application/xml');
      const paras = Array.from(parsed.getElementsByTagName('w:p'))
        .map((p) =>
          Array.from(p.getElementsByTagName('w:t'))
            .map((t) => t.textContent || '')
            .join('')
        )
        .filter((line) => line.trim().length > 0);
      return {
        name: file.name,
        format: 'docx',
        contentText: paras.join('\n\n'),
      };
    }
  }

  if (ext === 'pptx') {
    const zip = await JSZip.loadAsync(await file.arrayBuffer());
    const slideNames = Object.keys(zip.files)
      .filter((k) => /^ppt\/slides\/slide\d+\.xml$/.test(k))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
    const slideTexts: string[] = [];
    for (const sName of slideNames) {
      const xml = await zip.file(sName)?.async('string');
      if (!xml) continue;
      const doc = new DOMParser().parseFromString(xml, 'application/xml');
      const runs = Array.from(doc.getElementsByTagName('a:t')).map((n) => n.textContent || '');
      if (runs.length > 0) {
        slideTexts.push(`Slide ${slideTexts.length + 1}:\n${runs.join(' ')}`);
      }
    }
    return {
      name: file.name,
      format: 'pptx',
      contentText: slideTexts.join('\n\n') || 'Empty PPTX deck',
    };
  }

  if (ext === 'pdf') {
    return {
      name: file.name,
      format: 'pdf',
      contentText: `Imported PDF: ${file.name} (${Math.max(1, Math.round(file.size / 1024))} KB). Add notes or use AI Transform to summarize or convert to DOCX/Markdown.`,
    };
  }

  const txt = await file.text();
  return {
    name: file.name,
    format: ext === 'md' ? 'md' : 'txt',
    contentText: txt.slice(0, 120_000),
  };
}
